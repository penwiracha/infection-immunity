/* ============================================================
   gen-vocab-seed.mjs — write supabase/seed.sql from the data layer.
   The question/lecture tag lists (niches, organisms, failure modes,
   cascade steps, host defects as diseases) come from data/*.js so the
   database and the static site share one vocabulary.
   Run:  node scripts/gen-vocab-seed.mjs
   Re-run after adding organisms; it upserts, so it is safe to re-apply.
   ============================================================ */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ctx = vm.createContext({});
for (const f of ["enums", "organisms", "host-defects", "cascades/extracellular",
                 "cascades/vesicular", "cascades/cytosolic", "cascades/surface"]) {
  vm.runInContext(readFileSync(join(ROOT, "data", f + ".js"), "utf8"), ctx);
}
const { ENUMS, ORGANISMS, HOST_DEFECTS, CASCADES } = ctx;

const decode = (s) => String(s)
  .replace(/&mdash;/g, "—").replace(/&ndash;/g, "–").replace(/&amp;/g, "&")
  .replace(/&gamma;/g, "γ").replace(/&alpha;/g, "α").replace(/&beta;/g, "β")
  .replace(/<[^>]+>/g, "");
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const rows = [];
const add = (kind, id, label, sort) => rows.push(`(${q(kind)}, ${q(id)}, ${q(decode(label))}, ${sort})`);

ENUMS.niches.forEach((n, i) => add("niche", n.id, n.name, i));
ENUMS.failureModes.forEach((f, i) => add("failure_mode", f, f, i));
[["1", "ศรว. group 1"], ["2", "ศรว. group 2"]].forEach(([id, l], i) => add("tier", id, l, i));
["remember", "understand", "apply", "analyse", "evaluate", "create"]
  .forEach((b, i) => add("bloom", b, b[0].toUpperCase() + b.slice(1), i));
["easy", "medium", "hard"].forEach((d, i) => add("difficulty", d, d[0].toUpperCase() + d.slice(1), i));
// Topics mirror the sections the revision site already teaches. Admins can add more.
[
  ["immune-response", "Immune response"], ["evasion", "Immune evasion / why defence fails"],
  ["disease", "Disease and clinical features"], ["transmission", "Transmission and life cycle"],
  ["microscopy", "Microscopy and identification"], ["taxonomy", "Classification"],
  ["treatment", "Treatment (mechanism)"], ["resistance", "Resistance (mechanism)"],
  ["host-defect", "Host defects / immunodeficiency"], ["immune-components", "Immune system components"],
  ["prevention", "Vaccines and prevention"]
].forEach(([id, l], i) => add("topic", id, l, i));
[...ORGANISMS].sort((a, b) => a.name.localeCompare(b.name)).forEach((o, i) => add("organism", o.id, o.name, i));
// Diseases: host defects for now; admins add clinical syndromes from the Overview tab.
HOST_DEFECTS.forEach((h, i) => add("disease", h.id, h.name, i));
let s = 0;
for (const c of Object.values(CASCADES)) {
  for (const st of c.steps || []) add("cascade_step", `${c.id}:${st.k}`, `${c.id} ${st.k} — ${st.t}`, s++);
}

const sql = `-- GENERATED by scripts/gen-vocab-seed.mjs — do not hand-edit; re-run the script.
-- Controlled vocabularies for lecture and question tags.
insert into public.vocab (kind, id, label, sort) values
${rows.join(",\n")}
on conflict (kind, id) do update set label = excluded.label, sort = excluded.sort;
`;
writeFileSync(join(ROOT, "supabase", "seed.sql"), sql);
console.log(`supabase/seed.sql: ${rows.length} vocabulary terms`);
